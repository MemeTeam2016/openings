// Optional: tiny static server (no dependencies). `npm run serve` -> http://localhost:5174
// Opening index.html directly works too; this is just an alternative.
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('.', import.meta.url));
const port = Number(process.env.PORT) || 5174;
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png' };
const allowed = new Set(['/index.html', '/dist/app.js', '/dist/app.css']);

createServer(async (req, res) => {
  let path = decodeURIComponent(new URL(req.url, 'http://x').pathname);
  if (path === '/') path = '/index.html';
  if (!allowed.has(path)) { res.writeHead(404); res.end('Not found'); return; }
  try {
    const body = await readFile(join(root, normalize(path)));
    res.writeHead(200, { 'Content-Type': (types[extname(path)] || 'application/octet-stream') + '; charset=utf-8', 'Cache-Control': 'no-store' });
    res.end(body);
  } catch {
    res.writeHead(404); res.end('Not found');
  }
}).listen(port, '127.0.0.1', () => console.log(`Opening Trainer: http://localhost:${port}`));
